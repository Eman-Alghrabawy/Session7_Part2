using System;
using System.Collections.Generic;
using System.Text;

namespace Session7_Part2
{
    public class Maths
    {
        public int Add(int x, int y)
        {
            return x + y;
        }

        public int Subtract(int x, int y)
        {
            return x - y;
        }

        public int Multiply(int x, int y)
        {
            return x * y;
        }

        public double Divide(int x, int y)
        {
            return (double)x / y;
        }
    }
}
